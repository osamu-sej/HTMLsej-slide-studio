// What can follow a word without changing what it is (強化する・強化した・簡単な・積極的に…).
const ENDINGS = ["しています", "しました", "します", "している", "した", "して", "する", "され", "な", "に", "の", "的", "を"];

/** The word as it is looked up: width, katakana/hiragana and case folded, an ending taken off. */
export function lookupKey(word) {
  return fold(String(word ?? "")).replace(/\s+/g, "");
}

const index = new Map();
for (const group of SYNONYM_GROUPS) {
  for (const word of group.slice(1)) {
    const key = lookupKey(word);
    if (!index.has(key)) index.set(key, []);
    if (!index.get(key).includes(group)) index.get(key).push(group);
  }
}

/** The key a word is found under: itself, or itself without an ending (強化する → 強化). */
function resolve(word) {
  const key = lookupKey(word);
  if (!key) return null;
  if (index.has(key)) return key;
  for (const ending of ENDINGS) {
    const tail = lookupKey(ending);
    if (key.length > tail.length && key.endsWith(tail)) {
      const stem = key.slice(0, key.length - tail.length);
      if (index.has(stem)) return stem;
    }
  }
  return null;
}

/**
 * The senses a word has in the thesaurus, each with the other words that can stand for it:
 * [{ label, words }]. A word may have several senses (the one it heads comes first); an unknown word has none.
 */
export function synonymsOf(word) {
  const stem = resolve(word);
  if (!stem) return [];
  const heads = (group) => (lookupKey(group[1]) === stem ? 0 : 1);
  return [...index.get(stem)].sort((a, b) => heads(a) - heads(b))
    .map((group) => ({ label: group[0], words: group.slice(1).filter((w) => lookupKey(w) !== stem) }))
    .filter((sense) => sense.words.length);
}
